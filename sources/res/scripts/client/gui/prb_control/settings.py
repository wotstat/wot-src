def convertFlagsToNames(flags):
    result = []
    for name, bit in _FUNCTIONAL_FLAG_NAMES.iteritems():
        if flags & bit > 0:
            result.append(name)

    if not result:
        result.append(b'UNDEFINED')
    return result


