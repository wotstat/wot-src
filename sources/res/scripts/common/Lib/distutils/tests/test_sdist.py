    @unittest.skipUnless(zlib, b'requires zlib')
    def test_get_file_list(self):
        dist, cmd = self.get_cmd()
        dist.package_data = {b'somecode': [b'*.txt']}
        self.write_file((self.tmp_dir, b'somecode', b'doc.txt'), b'#')
        cmd.formats = [b'gztar']
        cmd.ensure_finalized()
        cmd.run()
        f = open(cmd.manifest)
        try:
            manifest = [line.strip() for line in f.read().split(b'\n') if line.strip() != b'']
        finally:
            f.close()

        self.assertEqual(len(manifest), 5)
        self.write_file((self.tmp_dir, b'somecode', b'doc2.txt'), b'#')
        build_py = dist.get_command_obj(b'build_py')
        build_py.finalized = False
        build_py.ensure_finalized()
        cmd.run()
        f = open(cmd.manifest)
        try:
            manifest2 = [line.strip() for line in f.read().split(b'\n') if line.strip() != b'']
        finally:
            f.close()

        self.assertEqual(len(manifest2), 6)
        self.assertIn(b'doc2.txt', manifest2[-1])
        return

