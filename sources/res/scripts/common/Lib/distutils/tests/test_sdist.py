SETUP_PY = b"\nfrom distutils.core import setup\nimport somecode\n\nsetup(name='fake')\n"
MANIFEST = b'# file GENERATED by distutils, do NOT edit\nREADME\nbuildout.cfg\ninroot.txt\nsetup.py\ndata%(sep)sdata.dt\nscripts%(sep)sscript.py\nsome%(sep)sfile.txt\nsome%(sep)sother_file.txt\nsomecode%(sep)s__init__.py\nsomecode%(sep)sdoc.dat\nsomecode%(sep)sdoc.txt\n'

class SDistTestCase(PyPIRCCommandTestCase):

    def setUp(self):
        super(SDistTestCase, self).setUp()
        self.old_path = os.getcwd()
        os.mkdir(join(self.tmp_dir, b'somecode'))
        os.mkdir(join(self.tmp_dir, b'dist'))
        self.write_file((self.tmp_dir, b'README'), b'xxx')
        self.write_file((self.tmp_dir, b'somecode', b'__init__.py'), b'#')
        self.write_file((self.tmp_dir, b'setup.py'), SETUP_PY)
        os.chdir(self.tmp_dir)
        return

    def tearDown(self):
        os.chdir(self.old_path)
        super(SDistTestCase, self).tearDown()
        return

    def get_cmd(self, metadata=None):
        if metadata is None:
            metadata = {b'name': b'fake', b'version': b'1.0', b'url': b'xxx', b'author': b'xxx', b'author_email': b'xxx'}
        dist = Distribution(metadata)
        dist.script_name = b'setup.py'
        dist.packages = [b'somecode']
        dist.include_package_data = True
        cmd = sdist(dist)
        cmd.dist_dir = b'dist'
        return (dist, cmd)

    @unittest.skipUnless(zlib, b'requires zlib')
    def test_prune_file_list(self):
        os.mkdir(join(self.tmp_dir, b'somecode', b'.svn'))
        self.write_file((self.tmp_dir, b'somecode', b'.svn', b'ok.py'), b'xxx')
        os.mkdir(join(self.tmp_dir, b'somecode', b'.hg'))
        self.write_file((self.tmp_dir, b'somecode', b'.hg',
         b'ok'), b'xxx')
        os.mkdir(join(self.tmp_dir, b'somecode', b'.git'))
        self.write_file((self.tmp_dir, b'somecode', b'.git',
         b'ok'), b'xxx')
        self.write_file((self.tmp_dir, b'somecode', b'.nfs0001'), b'xxx')
        dist, cmd = self.get_cmd()
        cmd.formats = [
         b'zip']
        cmd.ensure_finalized()
        cmd.run()
        dist_folder = join(self.tmp_dir, b'dist')
        files = os.listdir(dist_folder)
        self.assertEqual(files, [b'fake-1.0.zip'])
        zip_file = zipfile.ZipFile(join(dist_folder, b'fake-1.0.zip'))
        try:
            content = zip_file.namelist()
        finally:
            zip_file.close()

        expected = [
         12, 13, 14, 15, 
         16, 17]
        self.assertEqual(sorted(content), [b'fake-1.0/' + x for x in expected])
        return

    @unittest.skipUnless(zlib, b'requires zlib')
    def test_make_distribution(self):
        dist, cmd = self.get_cmd()
        cmd.formats = [
         b'gztar', b'tar']
        cmd.ensure_finalized()
        cmd.run()
        dist_folder = join(self.tmp_dir, b'dist')
        result = os.listdir(dist_folder)
        result.sort()
        self.assertEqual(result, [b'fake-1.0.tar', b'fake-1.0.tar.gz'])
        os.remove(join(dist_folder, b'fake-1.0.tar'))
        os.remove(join(dist_folder, b'fake-1.0.tar.gz'))
        cmd.formats = [
         b'tar', b'gztar']
        cmd.ensure_finalized()
        cmd.run()
        result = os.listdir(dist_folder)
        result.sort()
        self.assertEqual(result, [b'fake-1.0.tar', b'fake-1.0.tar.gz'])
        return

